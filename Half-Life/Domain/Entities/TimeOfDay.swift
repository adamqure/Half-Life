import Foundation

/// One minute on the clock, and the part of the day it falls in.
nonisolated struct TimeOfDay: Sendable, Equatable {
    /// The moment this time of day is for.
    let date: Date
    /// The part of the day `date` falls in, in the user's calendar.
    let period: DayPeriod
}
