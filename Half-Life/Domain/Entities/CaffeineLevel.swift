import Foundation

/// The caffeine in the body at one moment: a single point on the decay curve.
nonisolated struct CaffeineLevel: Sendable, Equatable {
    /// The moment this level is for.
    let date: Date
    /// The caffeine in the body at that moment, in milligrams. Never negative.
    let milligrams: Double
}
