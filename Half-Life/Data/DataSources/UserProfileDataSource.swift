/// Reads the user's profile from storage.
///
/// An implementation is the only code that touches the profile's storage (constitution Article I.14). See the Today
/// Screen article.
protocol UserProfileDataSource: Sendable {
    /// Returns the stored profile, or `nil` if nothing has been stored.
    func storedProfile() -> UserProfile?
}
