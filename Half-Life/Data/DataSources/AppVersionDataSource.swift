/// The only source of the app's version and build.
///
/// ``LiveAppVersionRepository`` reads it. The Settings article lists its requirements, VER-1 and VER-2.
protocol AppVersionDataSource: Sendable {
    /// Returns the app's version and build, or `nil` unless both are known.
    func appVersion() -> AppVersion?
}
